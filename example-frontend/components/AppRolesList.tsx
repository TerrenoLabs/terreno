import {useAdminRpc, useAdminRpcMutation, useAdminRpcQuery} from "@terreno/admin-frontend";
import {Badge, Box, Button, CheckBox, Heading, Modal, Spinner, Text, TextField} from "@terreno/ui";
import React, {useCallback, useMemo, useState} from "react";

/**
 * App-specific roles screen. Unlike `AdminRolesList` from `@terreno/admin-frontend`, it hides
 * model (CRUD) permissions and shows only the named permission checks the app makes, such as
 * `admin.access` or `clinicalIntake.signoff`. Model permissions already on a role are kept
 * unchanged when the role is saved. Pass `showAllPermissions` to also show and edit model
 * permissions.
 */

type AdminRpc = NonNullable<ReturnType<typeof useAdminRpc>>;

interface AppRolesListProps {
  /** Admin RPC client for the RBAC endpoints. Defaults to the one `AdminProvider` supplies. */
  rpc?: AdminRpc;
  /** Show model (CRUD) permissions alongside permission checks. Defaults to false. */
  showAllPermissions?: boolean;
}

interface RbacRoleRow {
  description?: string;
  displayName: string;
  isLocked?: boolean;
  isSealed?: boolean;
  name: string;
  permissions?: Record<string, string[]>;
}

type RbacStatements = Record<string, readonly string[]>;

type RolesResponse = RbacRoleRow[] | {data?: RbacRoleRow[]} | undefined;

type StatementsResponse =
  | {data?: {statements?: RbacStatements}; statements?: RbacStatements}
  | undefined;

interface RoleFormState {
  description: string;
  displayName: string;
  name: string;
  permissions: Record<string, string[]>;
}

const EMPTY_ROLE_FORM: RoleFormState = {
  description: "",
  displayName: "",
  name: "",
  permissions: {},
};

const RBAC_ROLES_URL = "/rbac/roles";
const RBAC_STATEMENTS_URL = "/rbac/statements";
const ROLES_TAG = "appRbacRoles";

// Actions generated by modelRouter CRUD or the admin model access selector. These are model
// permissions, not specific checks, so this screen never shows them.
const MODEL_ACTIONS = new Set([
  "create",
  "delete",
  "list",
  "read",
  "update",
  "write",
  "writeOwned",
]);

const isPermissionCheck = (action: string): boolean => !MODEL_ACTIONS.has(action);

const normalizeRoles = (data: RolesResponse): RbacRoleRow[] => {
  if (Array.isArray(data)) {
    return data;
  }
  return data?.data ?? [];
};

const normalizeStatements = (data: StatementsResponse): RbacStatements => {
  return data?.statements ?? data?.data?.statements ?? {};
};

/** Keeps only resources with at least one permission check, sorted by resource name. */
const visiblePermissions = ({
  permissions,
  showAll,
}: {
  permissions: Record<string, readonly string[]>;
  showAll: boolean;
}): [string, string[]][] => {
  return Object.keys(permissions)
    .sort((a, b) => a.localeCompare(b))
    .map((resource): [string, string[]] => [
      resource,
      (permissions[resource] ?? [])
        .filter((action) => showAll || isPermissionCheck(action))
        .sort((a, b) => a.localeCompare(b)),
    ])
    .filter(([, actions]) => actions.length > 0);
};

const clonePermissions = (permissions?: Record<string, string[]>): Record<string, string[]> => {
  return Object.fromEntries(
    Object.entries(permissions ?? {}).map(([resource, actions]) => [resource, [...actions]])
  );
};

const errorMessage = (failure: unknown, fallback: string): string => {
  const data = (failure as {data?: {detail?: string; title?: string}})?.data;
  return data?.detail ?? data?.title ?? fallback;
};

const PermissionCheckRows: React.FC<{
  permissions: Record<string, readonly string[]>;
  showAll: boolean;
  testIDPrefix: string;
}> = ({permissions, showAll, testIDPrefix}) => {
  const rows = visiblePermissions({permissions, showAll});
  if (rows.length === 0) {
    return (
      <Text color="secondaryLight" size="sm" testID={`${testIDPrefix}-empty`}>
        {showAll ? "No permissions granted." : "No permission checks granted."}
      </Text>
    );
  }
  return (
    <Box gap={1}>
      {rows.map(([resource, actions]) => (
        <Box
          alignItems="center"
          direction="row"
          gap={2}
          key={resource}
          testID={`${testIDPrefix}-${resource}`}
          wrap
        >
          <Box minWidth={200}>
            <Text bold size="sm">
              {resource}
            </Text>
          </Box>
          <Box direction="row" gap={1} wrap>
            {actions.map((action) => (
              <Badge
                key={action}
                status="info"
                testID={`${testIDPrefix}-${resource}-${action}`}
                value={action}
              />
            ))}
          </Box>
        </Box>
      ))}
    </Box>
  );
};

export const AppRolesList: React.FC<AppRolesListProps> = ({
  rpc: rpcOverride,
  showAllPermissions = false,
}) => {
  const contextRpc = useAdminRpc();
  const rpc = rpcOverride ?? contextRpc;
  const rolesQuery = useAdminRpcQuery<RolesResponse>({
    providesTags: [ROLES_TAG],
    rpc,
    url: RBAC_ROLES_URL,
  });
  const statementsQuery = useAdminRpcQuery<StatementsResponse>({rpc, url: RBAC_STATEMENTS_URL});
  const [mutateRole, {isLoading: isSaving}] = useAdminRpcMutation(rpc, {
    invalidatesTags: [ROLES_TAG],
  });

  const roles = normalizeRoles(rolesQuery.data);
  const statements = useMemo(
    () => normalizeStatements(statementsQuery.data),
    [statementsQuery.data]
  );
  const statementChecks = useMemo(
    () => visiblePermissions({permissions: statements, showAll: showAllPermissions}),
    [showAllPermissions, statements]
  );

  const [editingRole, setEditingRole] = useState<RbacRoleRow | null>(null);
  const [form, setForm] = useState<RoleFormState>(EMPTY_ROLE_FORM);
  const [isFormVisible, setIsFormVisible] = useState(false);
  const [saveError, setSaveError] = useState<string | null>(null);

  const handleCreate = useCallback((): void => {
    setEditingRole(null);
    setForm(EMPTY_ROLE_FORM);
    setSaveError(null);
    setIsFormVisible(true);
  }, []);

  const handleEdit = useCallback((role: RbacRoleRow): void => {
    setEditingRole(role);
    setForm({
      description: role.description ?? "",
      displayName: role.displayName,
      name: role.name,
      permissions: clonePermissions(role.permissions),
    });
    setSaveError(null);
    setIsFormVisible(true);
  }, []);

  const handleDismiss = useCallback((): void => {
    setIsFormVisible(false);
    setSaveError(null);
  }, []);

  const handleFieldChange = useCallback(
    (field: "description" | "displayName" | "name", value: string): void => {
      setForm((current) => ({...current, [field]: value}));
    },
    []
  );

  const handlePermissionToggle = useCallback((resource: string, action: string): void => {
    setForm((current) => {
      const currentActions = current.permissions[resource] ?? [];
      const nextActions = currentActions.includes(action)
        ? currentActions.filter((item) => item !== action)
        : [...currentActions, action].sort();
      const permissions = {...current.permissions};
      if (nextActions.length === 0) {
        Reflect.deleteProperty(permissions, resource);
      } else {
        permissions[resource] = nextActions;
      }
      return {...current, permissions};
    });
  }, []);

  const handleSave = useCallback(async (): Promise<void> => {
    const name = form.name.trim();
    const displayName = form.displayName.trim();
    if (!name || !displayName) {
      setSaveError("Name and display name are required.");
      return;
    }
    setSaveError(null);
    const description = form.description.trim();
    try {
      if (editingRole) {
        await mutateRole({
          body: {
            description: description === "" ? null : description,
            displayName,
            permissions: form.permissions,
          },
          method: "PATCH",
          url: `${RBAC_ROLES_URL}/${encodeURIComponent(editingRole.name)}`,
        }).unwrap();
      } else {
        await mutateRole({
          body: {
            description: description || undefined,
            displayName,
            name,
            permissions: form.permissions,
          },
          method: "POST",
          url: RBAC_ROLES_URL,
        }).unwrap();
      }
      setIsFormVisible(false);
    } catch (failure: unknown) {
      setSaveError(errorMessage(failure, "Failed to save role."));
    }
  }, [editingRole, form, mutateRole]);

  if (rolesQuery.isLoading) {
    return (
      <Box alignItems="center" padding={4} testID="admin-roles-loading">
        <Spinner />
      </Box>
    );
  }

  if (rolesQuery.error) {
    return (
      <Box padding={4} testID="admin-roles-error">
        <Text color="error">Failed to load roles.</Text>
      </Box>
    );
  }

  return (
    <Box direction="column" flex="grow" minHeight={0} testID="admin-roles-list">
      <Box
        alignItems="center"
        direction="row"
        gap={2}
        justifyContent="between"
        paddingX={4}
        paddingY={3}
      >
        <Heading size="lg">Roles</Heading>
        <Button
          iconName="plus"
          onClick={handleCreate}
          testID="admin-roles-add-button"
          text="Add role"
        />
      </Box>
      {/* Scrolls the role cards so a long list cannot push "Add role" out of reach. */}
      <Box flex="grow" minHeight={0} scroll testID="admin-roles-scroll">
        <Box direction="column" gap={3} paddingX={4} paddingY={2}>
          {roles.length === 0 ? (
            <Text>No roles found.</Text>
          ) : (
            roles.map((role) => (
              <Box
                border="default"
                direction="column"
                gap={2}
                key={role.name}
                padding={3}
                rounding="md"
                testID={`admin-roles-item-${role.name}`}
              >
                <Box alignItems="center" direction="row" gap={2} justifyContent="between">
                  <Box alignItems="center" direction="row" gap={2}>
                    <Text bold size="md">
                      {role.displayName}
                    </Text>
                    {role.isLocked ? <Badge secondary status="info" value="locked" /> : null}
                    {role.isSealed ? <Badge secondary status="warning" value="sealed" /> : null}
                  </Box>
                  <Button
                    disabled={role.isSealed}
                    iconName="pen"
                    onClick={() => handleEdit(role)}
                    testID={`admin-roles-edit-${role.name}`}
                    text="Edit"
                    variant="outline"
                  />
                </Box>
                <Text color="secondaryLight" size="sm">
                  {role.name}
                </Text>
                {role.description ? <Text size="sm">{role.description}</Text> : null}
                <PermissionCheckRows
                  permissions={role.permissions ?? {}}
                  showAll={showAllPermissions}
                  testIDPrefix={`admin-roles-item-${role.name}-permission`}
                />
              </Box>
            ))
          )}

          <Box border="default" gap={2} padding={3} rounding="md" testID="admin-permissions-list">
            <Heading size="md">Available permissions</Heading>
            {statementsQuery.isLoading ? <Spinner /> : null}
            {statementsQuery.error ? <Text color="error">Failed to load permissions.</Text> : null}
            {!statementsQuery.isLoading && !statementsQuery.error ? (
              <PermissionCheckRows
                permissions={statements}
                showAll={showAllPermissions}
                testIDPrefix="admin-permissions"
              />
            ) : null}
          </Box>
        </Box>
      </Box>

      <Modal
        onDismiss={handleDismiss}
        primaryButtonDisabled={isSaving}
        primaryButtonOnClick={handleSave}
        primaryButtonText={editingRole ? "Save role" : "Create role"}
        secondaryButtonOnClick={handleDismiss}
        secondaryButtonText="Cancel"
        size="lg"
        testID="admin-role-modal"
        testIDs={{primaryButton: "admin-role-save-button"}}
        title={editingRole ? `Edit ${editingRole.displayName}` : "Add role"}
        visible={isFormVisible}
      >
        <Box gap={3} testID="admin-role-form">
          {saveError ? (
            <Text color="error" testID="admin-role-save-error">
              {saveError}
            </Text>
          ) : null}
          <Box gap={4} maxHeight={360} overflow="scroll" padding={2}>
            <TextField
              disabled={Boolean(editingRole)}
              onChange={(value) => handleFieldChange("name", value)}
              testID="admin-role-name"
              title="Name"
              value={form.name}
            />
            <TextField
              onChange={(value) => handleFieldChange("displayName", value)}
              testID="admin-role-display-name"
              title="Display name"
              value={form.displayName}
            />
            <TextField
              onChange={(value) => handleFieldChange("description", value)}
              testID="admin-role-description"
              title="Description"
              value={form.description}
            />
            <Box gap={2} testID="admin-role-permissions">
              <Heading size="sm">Permissions</Heading>
              {statementChecks.map(([resource, actions]) => (
                <Box gap={1} key={resource}>
                  <Text bold>{resource}</Text>
                  <Box direction="row" gap={3} wrap>
                    {actions.map((action) => (
                      <Box
                        accessibilityHint={`Toggles the ${action} permission for ${resource}`}
                        accessibilityLabel={`${resource} ${action}`}
                        alignItems="center"
                        direction="row"
                        gap={1}
                        key={`${resource}:${action}`}
                        onClick={() => handlePermissionToggle(resource, action)}
                        testID={`admin-role-permission-${resource}-${action}`}
                      >
                        <CheckBox
                          selected={form.permissions[resource]?.includes(action) ?? false}
                        />
                        <Text>{action}</Text>
                      </Box>
                    ))}
                  </Box>
                </Box>
              ))}
            </Box>
          </Box>
        </Box>
      </Modal>
    </Box>
  );
};
