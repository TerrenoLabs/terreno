import {refName, toPascalCase, upperFirst} from "./hookNames";
import {assertTsIdentifier, emitTsPropertyKey, emitTsString} from "./safeIdentifiers";
import type {
  CodegenConfigFile,
  DiscoveredOperation,
  OpenApiDocument,
  OpenApiParameter,
  OpenApiSchema,
} from "./types";

const GENERATED_HEADER = `// GENERATED by @terreno/syncdb (terreno-syncdb-codegen --api-out). Do not edit.
// Typed request hooks for every non-synced @terreno/api route. Synced collections use
// the collection hooks from the sync SDK instead. Hook names follow the RTK codegen
// convention (useGetAuthMeQuery, usePatchAuthMeMutation, useLazy…Query).
// biome-ignore-all lint/suspicious/noConfusingVoidType: no-argument operations type their argument as void so callers can omit it
`;

/** Names the generated module declares or imports itself. */
const RESERVED_NAMES = [
  "ApiRequestArgs",
  "ApiSdkLazyOptions",
  "ApiSdkQueryOptions",
  "UseApiMutationOptions",
  "UseApiMutationResult",
  "UseApiQueryOptions",
  "UseApiQueryResult",
  "UseLazyApiQueryOptions",
  "UseLazyApiQueryResult",
];

interface EmitContext {
  spec: OpenApiDocument;
  /** Component schema name → emitted TypeScript identifier. */
  referenced: Map<string, string>;
  /** Emitted identifier → component schema name, to catch sanitization collisions. */
  identifiers: Map<string, string>;
}

const componentIdentifier = (name: string): string =>
  assertTsIdentifier({
    label: "component schema name",
    value: /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)
      ? name
      : toPascalCase(name.replace(/[^A-Za-z0-9]+/g, "_")),
  });

const resolveRef = (ctx: EmitContext, schema: OpenApiSchema): OpenApiSchema => {
  const name = refName(schema.$ref);
  return (name && ctx.spec.components?.schemas?.[name]) || schema;
};

/** True when `type` has a `|` or `&` outside any braces, brackets, or parens. */
const hasTopLevelOperator = (type: string): boolean => {
  let depth = 0;
  for (const char of type) {
    if ("{[(<".includes(char)) {
      depth += 1;
    } else if ("}])>".includes(char)) {
      depth -= 1;
    } else if (depth === 0 && (char === "|" || char === "&")) {
      return true;
    }
  }
  return false;
};

/** Parenthesize a union/intersection so it composes safely inside `&`, `|`, or `[]`. */
const group = (type: string): string => (hasTopLevelOperator(type) ? `(${type})` : type);

const tsType = (ctx: EmitContext, schema: OpenApiSchema | undefined, indent: string): string => {
  if (!schema) {
    return "unknown";
  }
  const nullable = schema.nullable ? " | null" : "";
  if (schema.$ref) {
    const name = refName(schema.$ref);
    if (!name || !ctx.spec.components?.schemas?.[name]) {
      return "unknown";
    }
    const identifier = componentIdentifier(name);
    const owner = ctx.identifiers.get(identifier);
    if (owner && owner !== name) {
      throw new Error(
        `Component schemas "${owner}" and "${name}" both become the type name "${identifier}".`
      );
    }
    ctx.identifiers.set(identifier, name);
    ctx.referenced.set(name, identifier);
    return `${identifier}${nullable}`;
  }
  if (schema.allOf?.length) {
    return schema.allOf.map((part) => group(tsType(ctx, part, indent))).join(" & ") + nullable;
  }
  const union = schema.oneOf ?? schema.anyOf;
  if (union?.length) {
    return union.map((part) => group(tsType(ctx, part, indent))).join(" | ") + nullable;
  }
  if (schema.enum?.length) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ") + nullable;
  }
  if (schema.type === "array") {
    const item = tsType(ctx, schema.items, indent);
    return `${group(item)}[]${nullable}`;
  }
  if (schema.type === "object" || schema.properties || schema.additionalProperties) {
    if (schema.properties && Object.keys(schema.properties).length > 0) {
      return objectBody(ctx, schema, indent) + nullable;
    }
    if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
      return `Record<string, ${tsType(ctx, schema.additionalProperties, indent)}>${nullable}`;
    }
    return `Record<string, unknown>${nullable}`;
  }
  if (schema.type === "integer" || schema.type === "number") {
    return `number${nullable}`;
  }
  if (schema.type === "boolean") {
    return `boolean${nullable}`;
  }
  if (schema.type === "string" || schema.type === "schemaobjectid") {
    return `string${nullable}`;
  }
  return "unknown";
};

const objectBody = (ctx: EmitContext, schema: OpenApiSchema, indent: string): string => {
  const required = new Set(schema.required ?? []);
  const lines = Object.entries(schema.properties ?? {}).map(([key, property]) => {
    const optional = required.has(key) ? "" : "?";
    return `${indent}  ${emitTsPropertyKey(key)}${optional}: ${tsType(ctx, property, `${indent}  `)};`;
  });
  return `{\n${lines.join("\n")}\n${indent}}`;
};

/** Path params come from the URL template; declared parameters only supply their types. */
const pathParamsOf = (operation: DiscoveredOperation): OpenApiParameter[] => {
  const declared = new Map(operation.pathParams.map((param) => [param.name, param]));
  return [...operation.path.matchAll(/\{([^}]+)\}/g)].map(
    ([, name]) => declared.get(name) ?? {in: "path", name, required: true, schema: {type: "string"}}
  );
};

const bodyType = (
  ctx: EmitContext,
  operation: DiscoveredOperation,
  indent = ""
): string | undefined => {
  if (!operation.body) {
    return undefined;
  }
  if (operation.body.mediaType === "multipart/form-data") {
    return "FormData";
  }
  if (operation.body.mediaType !== "application/json") {
    return "Blob | string";
  }
  return tsType(ctx, operation.body.schema, indent);
};

interface ArgShape {
  /** TypeScript type of the hook argument. */
  type: string;
  /** The argument may be omitted (a lone optional query param or optional body). */
  optional: boolean;
  /** Request-builder parameter list (`arg: X` or empty). */
  param: string;
  /** Expression for a path param, query param, or the body. */
  accessor: (kind: "path" | "query" | "body", name?: string) => string;
}

/** The flattened argument is the value itself (and, with no argument, nothing reads it). */
const wholeArg = (): string => "arg";

/** RTK codegen `flattenArg`: a single path param, query param, or body is the argument itself. */
const argShape = (ctx: EmitContext, operation: DiscoveredOperation, argsName: string): ArgShape => {
  const pathParams = pathParamsOf(operation);
  const body = bodyType(ctx, operation);
  const count = pathParams.length + operation.queryParams.length + (body ? 1 : 0);
  if (count === 0) {
    return {accessor: wholeArg, optional: true, param: "", type: "void"};
  }
  if (count === 1) {
    const [only] = [...pathParams, ...operation.queryParams];
    const type = body ?? tsType(ctx, only?.schema ?? {type: "string"}, "");
    const optional = body
      ? operation.body?.required === false
      : only?.in === "query" && !only.required;
    return {
      accessor: wholeArg,
      optional,
      param: optional ? `arg?: ${argsName}` : `arg: ${argsName}`,
      type: optional ? `${type} | undefined` : type,
    };
  }
  const lines = [
    ...pathParams.map(
      (param) =>
        `  ${emitTsPropertyKey(param.name ?? "")}: ${tsType(ctx, param.schema ?? {type: "string"}, "  ")};`
    ),
    ...operation.queryParams.map(
      (param) =>
        `  ${emitTsPropertyKey(param.name ?? "")}${param.required ? "" : "?"}: ${tsType(ctx, param.schema, "  ")};`
    ),
    ...(body
      ? [
          `  body${operation.body?.required === false ? "?" : ""}: ${bodyType(ctx, operation, "  ")};`,
        ]
      : []),
  ];
  return {
    accessor: (kind, name) =>
      kind === "body"
        ? "arg.body"
        : `arg${/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name ?? "") ? `.${name}` : `[${JSON.stringify(name)}]`}`,
    optional: false,
    param: `arg: ${argsName}`,
    type: `{\n${lines.join("\n")}\n}`,
  };
};

/** Response type after the client's envelope unwrapping (`{data}` → data; lists keep `more`). */
const responseType = (ctx: EmitContext, operation: DiscoveredOperation): string => {
  if (operation.response === null) {
    return "null";
  }
  if (!operation.response) {
    return "unknown";
  }
  const resolved = resolveRef(ctx, operation.response);
  const data = resolved.properties?.data;
  if (!data || resolved.properties?.more) {
    return tsType(ctx, operation.response, "");
  }
  // The client unwraps only a truthy `data`; promise the bare type only when that is certain.
  const dataSchema = resolveRef(ctx, data);
  const alwaysTruthy =
    (resolved.required ?? []).includes("data") &&
    !data.nullable &&
    !dataSchema.nullable &&
    (dataSchema.type === "object" || dataSchema.type === "array" || Boolean(dataSchema.properties));
  const dataType = tsType(ctx, data, "");
  return alwaysTruthy
    ? dataType
    : `${group(dataType)} | ${group(tsType(ctx, operation.response, ""))}`;
};

const emitRequestBuilder = (
  operation: DiscoveredOperation,
  shape: ArgShape,
  requestName: string
): string => {
  const url = operation.path.replace(/\{([^}]+)\}/g, (_match, name: string) => {
    const value = `String(${shape.accessor("path", name)})`;
    // Wildcard params span segments, so encode each segment and keep the slashes.
    return operation.wildcardParams.includes(name)
      ? `\${${value}.split("/").map(encodeURIComponent).join("/")}`
      : `\${encodeURIComponent(${value})}`;
  });
  const fields = [
    `    method: ${emitTsString(operation.method.toUpperCase())},`,
    `    url: \`${url}\`,`,
  ];
  if (operation.queryParams.length > 0) {
    const entries = operation.queryParams.map(
      (param) => `${emitTsPropertyKey(param.name ?? "")}: ${shape.accessor("query", param.name)}`
    );
    fields.push(`    params: {${entries.join(", ")}},`);
  }
  if (operation.body) {
    fields.push(`    body: ${shape.accessor("body")},`);
  }
  return `export const ${requestName} = (${shape.param}): ApiRequestArgs => ({\n${fields.join("\n")}\n});`;
};

const emitHooks = (
  operation: DiscoveredOperation,
  names: {pascal: string; args: string; res: string; request: string},
  shape: ArgShape
): string => {
  const tags = `[${operation.tags.map((tag) => emitTsString(tag)).join(", ")}]`;
  const call = shape.param ? `${names.request}(arg)` : `${names.request}()`;
  const summary = operation.summary ? `/** ${operation.summary.replace(/\*\//g, "*\\/")} */\n` : "";
  if (operation.method === "get") {
    const queryParam = shape.param
      ? `arg${shape.optional ? "?" : ""}: ${names.args}`
      : `_arg?: ${names.args}`;
    const lazyMap = shape.param ? names.request : `(): ApiRequestArgs => ${names.request}()`;
    return `${summary}export const use${names.pascal}Query = (
  ${queryParam},
  options: ApiSdkQueryOptions<${names.res}> = {}
): UseApiQueryResult<${names.res}> =>
  useApiQuery<${names.res}>(${call}, {...options, providesTags: ${tags}});

export const useLazy${names.pascal}Query = (
  options: ApiSdkLazyOptions<${names.res}> = {}
): UseLazyApiQueryResult<${names.res}, ${names.args}> =>
  useLazyApiQuery<${names.res}, ${names.args}>({...options, providesTags: ${tags}, toRequest: ${lazyMap}});`;
  }
  const mutationMap = shape.param ? names.request : `(): ApiRequestArgs => ${names.request}()`;
  return `${summary}export const use${names.pascal}Mutation = (
  options: UseApiMutationOptions<${names.args}, ${names.res}> = {}
): UseApiMutationResult<${names.args}, ${names.res}> =>
  useApiMutation<${names.args}, ${names.res}>(${mutationMap}, {invalidatesTags: ${tags}, ...options});`;
};

const emitComponents = (ctx: EmitContext): string[] => {
  const emitted = new Set<string>();
  const blocks: string[] = [];
  // Emitting a component can reference more components; repeat until none are new.
  let pending = [...ctx.referenced.keys()].filter((name) => !emitted.has(name));
  while (pending.length > 0) {
    for (const name of pending) {
      emitted.add(name);
      const schema = ctx.spec.components?.schemas?.[name] ?? {};
      const identifier = componentIdentifier(name);
      const isObject =
        schema.properties && Object.keys(schema.properties).length > 0 && !schema.nullable;
      blocks.push(
        isObject
          ? `export interface ${identifier} ${objectBody(ctx, schema, "")}`
          : `export type ${identifier} = ${tsType(ctx, schema, "")};`
      );
    }
    pending = [...ctx.referenced.keys()].filter((name) => !emitted.has(name));
  }
  return blocks;
};

/** Emit the API SDK module: component types, per-operation types, request builders, hooks. */
export const emitApi = ({
  config,
  operations,
  spec,
}: {
  config?: CodegenConfigFile;
  operations: DiscoveredOperation[];
  spec: OpenApiDocument;
}): string => {
  const ctx: EmitContext = {identifiers: new Map(), referenced: new Map(), spec};
  const reactImport = config?.sdkImportPath ?? "@terreno/syncdb/react";
  const apiImport = config?.apiImportPath ?? "@terreno/syncdb/api";
  const operationBlocks: string[] = [];
  const generatedNames = new Set(RESERVED_NAMES);

  for (const operation of [...operations].sort((a, b) => a.name.localeCompare(b.name))) {
    const pascal = assertTsIdentifier({label: "operation name", value: upperFirst(operation.name)});
    const names = {
      args: `${pascal}Args`,
      pascal,
      request: `${operation.name}Request`,
      res: `${pascal}Res`,
    };
    generatedNames.add(names.args);
    generatedNames.add(names.res);
    const shape = argShape(ctx, operation, names.args);
    operationBlocks.push(
      [
        `export type ${names.args} = ${shape.type};`,
        `export type ${names.res} = ${responseType(ctx, operation)};`,
        emitRequestBuilder(operation, shape, names.request),
        emitHooks(operation, names, shape),
      ].join("\n\n")
    );
  }

  const componentBlocks = emitComponents(ctx);
  const shadowed = [...ctx.identifiers.keys()].find((identifier) => generatedNames.has(identifier));
  if (shadowed) {
    throw new Error(
      `Component schema "${ctx.identifiers.get(shadowed)}" becomes "${shadowed}", which the SDK already declares. Rename the schema.`
    );
  }
  return [
    GENERATED_HEADER,
    `import type {ApiRequestArgs} from ${emitTsString(apiImport)};`,
    `import {
  type UseApiMutationOptions,
  type UseApiMutationResult,
  type UseApiQueryOptions,
  type UseApiQueryResult,
  type UseLazyApiQueryOptions,
  type UseLazyApiQueryResult,
  useApiMutation,
  useApiQuery,
  useLazyApiQuery,
} from ${emitTsString(reactImport)};`,
    "",
    `type ApiSdkQueryOptions<T> = Omit<UseApiQueryOptions<T, T>, "providesTags" | "transformResponse">;`,
    `type ApiSdkLazyOptions<T> = Omit<UseLazyApiQueryOptions<T, never>, "providesTags" | "toRequest">;`,
    "",
    componentBlocks.join("\n\n"),
    "",
    operationBlocks.join("\n\n"),
    "",
  ].join("\n");
};
